import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { storageCases } from "./cases.js";
import { sq8Cases } from "./optional-cases.js";
import type { TargetReport } from "./types.js";

function cell(value: string): string {
  return value.replaceAll("|", "\\|").replace(/[\r\n]/g, " ");
}

/** Deterministic scenario/feature × target matrix; missing results are never shown as passes. */
export function generateMatrix(reports: readonly TargetReport[]): string {
  const sorted = [...reports].sort((a, b) => a.target.localeCompare(b.target));
  const tests = [
    ...new Set([
      ...storageCases.map((scenario) => scenario.id),
      ...(sorted.some((report) => report.target.startsWith("sparq-"))
        ? sq8Cases.map((scenario) => scenario.id)
        : []),
      ...["accessControl", "trash", "versioning", "typeIndex"].map(
        (feature) => `claims:${feature}`,
      ),
      ...sorted.flatMap((report) => report.results.map((row) => row.test)),
    ]),
  ].sort();
  const lines = [
    "<!-- AUTHORED-BY Codex GPT-6.1-Sol -->",
    "<!-- Generated by pnpm run conformance; do not edit by hand. -->",
    "# Storage conformance matrix",
    "",
    `| Scenario / feature | ${sorted.map((report) => cell(report.target)).join(" | ")} |`,
    `| --- | ${sorted.map(() => "---").join(" | ")} |`,
  ];
  for (const test of tests) {
    lines.push(
      `| ${cell(test)} | ${sorted
        .map((report) => {
          const row = report.results.find((candidate) => candidate.test === test);
          return row ? cell(`${row.status}${row.reason ? ` (${row.reason})` : ""}`) : "not-run";
        })
        .join(" | ")} |`,
    );
  }
  return `${lines.join("\n")}\n`;
}

/** Write sanitized per-target JSON and a matrix of exactly this run's targets. */
export async function writeReports(
  reports: readonly TargetReport[],
  directory: string,
): Promise<void> {
  await mkdir(join(directory, "reports"), { recursive: true });
  for (const report of reports) {
    if (!/^[a-z][a-z0-9-]*$/.test(report.target)) throw new TypeError("Invalid target name");
    await writeFile(
      join(directory, "reports", `${report.target}.json`),
      `${JSON.stringify(report.results, null, 2)}\n`,
    );
  }
  await writeFile(join(directory, "MATRIX.md"), generateMatrix(reports));
}
