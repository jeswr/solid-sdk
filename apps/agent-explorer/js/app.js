// Router, navigation, theme, evidence banner and keyboard for the agent explorer. Classic script.
(function () {
  'use strict';
  var AX = window.AX;
  var esc = AX.esc;
  var view = document.getElementById('view');
  var nav = document.getElementById('nav');
  var current = null;

  var VIEWS = [
    { id: 'explore', label: 'Explore' },
    { id: 'architecture', label: 'Architecture' },
    { id: 'message', label: 'Message' },
    { id: 'layers', label: 'Layers' },
    { id: 'usecases', label: 'Use cases', when: function () { return !!AX.data.useCases; } },
    { id: 'requirements', label: 'Requirements', when: function () { return !!AX.model.requirements; } },
    { id: 'specs', label: 'Specifications' },
    { id: 'tests', label: 'Evaluation' },
    { id: 'roadmap', label: 'Roadmap', when: function () { return !!AX.data.roadmap; } },
  ].filter(function (v) { return !v.when || v.when(); });
  AX.views = VIEWS;

  AX.lastExploreHash = AX.buildHash('explore', {});
  nav.innerHTML = VIEWS.map(function (v) {
    return '<a href="#/' + v.id + '" data-view="' + v.id + '"' + ' data-anchor="nav.' + v.id + '">' + esc(v.label) + '</a>';
  }).join('');
  AX.onExploreHash = function (h) {
    var a = nav.querySelector('[data-view="explore"]');
    if (a) a.setAttribute('href', h);
  };

  // ---- Evidence banner ---------------------------------------------------------
  function renderEvidence(trace) {
    var el = document.getElementById('evidence');
    var badge = '';
    if (trace) {
      if (trace.isFixture) badge = '<span class="fixture">Development fixture, not a real run</span>';
      else badge = '<span class="real" title="' + esc('Generated by ' + (trace.generated.core || 'the runtime') + ' at commit ' + (trace.generated.commit || 'unknown')) + '">Real run' + (trace.generated.commit ? ' <code>' + esc(String(trace.generated.commit).slice(0, 7)) + '</code>' : '') + '</span>';
    } else {
      var nReal = AX.traces.filter(function (t) { return !t.isFixture; }).length;
      var nFix = AX.traces.length - nReal;
      if (nReal) badge += '<span class="real">' + nReal + (nReal === 1 ? ' real run' : ' real runs') + '</span>';
      if (nFix) badge += '<span class="fixture">' + nFix + (nFix === 1 ? ' development fixture' : ' development fixtures') + '</span>';
    }
    el.innerHTML = badge + '<span class="level">' + esc(AX.model.evidenceLevel || '') + '</span>';
  }
  document.addEventListener('ax:trace', function (e) { if (current === 'explore') renderEvidence(e.detail); });

  // ---- Router -------------------------------------------------------------------
  function route() {
    var st = AX.parseHash();
    var id = VIEWS.some(function (v) { return v.id === st.view; }) ? st.view : 'explore';
    nav.querySelectorAll('a').forEach(function (a) {
      if (a.dataset.view === id) a.setAttribute('aria-current', 'page');
      else a.removeAttribute('aria-current');
    });
    if (id === 'explore') {
      if (current === 'explore' && AX.explore.isMounted()) {
        AX.explore.apply(st.params);
      } else {
        unmount();
        current = 'explore';
        view.className = 'view mode-explore';
        AX.explore.mount(view, st.params);
      }
      return;
    }
    if (current === 'explore') AX.explore.unmount();
    document.body.classList.remove('present');
    var sameView = current === id;
    current = id;
    view.className = 'view mode-' + id;
    renderEvidence(null);
    var r = AX.render && AX.render[id];
    if (!r) { view.innerHTML = '<div class="page"><p class="empty">This view is not available.</p></div>'; return; }
    var scroll = sameView ? view.scrollTop : 0;
    r(view, st.params);
    view.scrollTop = scroll;
    if (st.params.select || st.params.at) {
      var target = view.querySelector('.sel, [data-sel-target]');
      if (st.params.at) target = document.getElementById(st.params.at) || target;
      if (target) target.scrollIntoView({ block: 'center', behavior: 'auto' });
    } else if (!sameView) {
      view.scrollTop = 0;
    }
  }
  function unmount() {
    if (current === 'explore' && AX.explore.isMounted()) AX.explore.unmount();
  }
  AX.route = route;
  // The address bar changed from outside (a typed link, back or forward): adopt it, unless it
  // is only the short mirror of where the page already is.
  function adopt() {
    var h = location.hash || '';
    if (h === AX.hash.cur) return;
    if (AX.hash.framed && AX.parseHash(h).view === AX.parseHash().view && h.indexOf('?') < 0) return;
    AX.hash.cur = h;
    route();
  }
  window.addEventListener('hashchange', adopt);
  window.addEventListener('popstate', adopt);
  // Every in-page link goes through AX.go, so it works where the host ignores hash changes.
  document.addEventListener('click', function (e) {
    if (e.defaultPrevented || e.button || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
    var a = e.target && e.target.closest ? e.target.closest('a[href^="#"]') : null;
    if (!a) return;
    e.preventDefault();
    AX.go(a.getAttribute('href'));
  });

  // ---- Theme ---------------------------------------------------------------------
  var THEMES = ['system', 'light', 'dark'];
  var themeBtn = document.getElementById('theme-btn');
  function applyTheme(t) {
    if (t === 'system') document.documentElement.removeAttribute('data-theme');
    else document.documentElement.setAttribute('data-theme', t);
    themeBtn.setAttribute('aria-label', 'Theme: ' + t);
    themeBtn.title = 'Theme: ' + t + '. Click to change.';
  }
  var theme = AX.store.get('ax-theme') || 'system';
  if (THEMES.indexOf(theme) < 0) theme = 'system';
  applyTheme(theme);
  themeBtn.addEventListener('click', function () {
    theme = THEMES[(THEMES.indexOf(theme) + 1) % THEMES.length];
    AX.store.set('ax-theme', theme);
    applyTheme(theme);
  });

  // ---- Keyboard ------------------------------------------------------------------
  document.addEventListener('keydown', function (e) {
    if (e.defaultPrevented || e.metaKey || e.ctrlKey || e.altKey) return;
    if (AX.tour && AX.tour.active()) return; // the tour handles its own keys
    if (current !== 'explore') return;
    var tag = (e.target && e.target.tagName) || '';
    if (/^(INPUT|SELECT|TEXTAREA)$/.test(tag)) return;
    var isBtn = tag === 'BUTTON' || tag === 'SUMMARY';
    if (e.key === 'ArrowRight') { AX.explore.move(1); e.preventDefault(); }
    else if (e.key === 'ArrowLeft') { AX.explore.move(-1); e.preventDefault(); }
    else if (e.key === 'Home') { AX.explore.home(); e.preventDefault(); }
    else if (e.key === 'End') { AX.explore.end(); e.preventDefault(); }
    else if ((e.key === ' ' || e.key === 'Spacebar') && !isBtn) { AX.explore.toggle(); e.preventDefault(); }
  });

  // ---- Start -----------------------------------------------------------------------
  document.getElementById('tour-btn').addEventListener('click', function () { if (AX.tour) AX.tour.start(); });
  route();
  if (AX.tour) AX.tour.maybeInvite();
})();
