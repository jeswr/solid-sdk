"""Run with the reference np_builder.py path; requires rdflib==7.1.4.

No pilot imports or personal data. Only publication-generation timestamps are
fixed after the unmodified reference CLI runs; identifiers are never rewritten.
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from rdflib import Dataset, Literal, Namespace
from rdflib.namespace import RDF, XSD

root = Path(__file__).parent / "fixtures"
np = Namespace("http://www.nanopub.org/nschema#")
prov = Namespace("http://www.w3.org/ns/prov#")
with tempfile.TemporaryDirectory() as temp:
    output = Path(temp) / "expected.trig"
    subprocess.run([sys.executable, sys.argv[1], str(root / "synthetic.claims.json"), "--out", str(output)], check=True)
    ds = Dataset()
    ds.parse(output, format="trig")
    ids = []
    for subject, _, _, head in ds.quads((None, RDF.type, np.Nanopublication, None)):
        graph = ds.graph(head)
        info = graph.value(subject, np.hasPublicationInfo)
        ds.graph(info).set((subject, prov.generatedAtTime, Literal("2026-10-25T12:00:00+00:00", datatype=XSD.dateTime)))
        ids.append({"id": str(subject), "assertionId": str(graph.value(subject, np.hasAssertion)), "provenanceId": str(graph.value(subject, np.hasProvenance)), "pubinfoId": str(info)})
    (root / "synthetic.ids.json").write_text(json.dumps(sorted(ids, key=lambda row: row["id"]), indent=2) + "\n")
    (root / "synthetic.expected.trig").write_text("# AUTHORED-BY Codex GPT-6.1-Sol — generated by the Python reference builder\n" + ds.serialize(format="trig"))
