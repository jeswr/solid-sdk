"""Run with the reference np_builder.py path; requires rdflib==7.1.4.

No pilot imports or personal data. Only publication-generation timestamps are
fixed after the unmodified reference CLI runs; identifiers are never rewritten.
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from rdflib import Dataset, Literal, Namespace
from rdflib.namespace import RDF, XSD

root = Path(__file__).parent / "fixtures"
np = Namespace("http://www.nanopub.org/nschema#")
prov = Namespace("http://www.w3.org/ns/prov#")
with tempfile.TemporaryDirectory() as temp:
    output = Path(temp) / "expected.trig"
    subprocess.run([sys.executable, sys.argv[1], str(root / "synthetic.claims.json"), "--out", str(output)], check=True)
    ds = Dataset()
    ds.parse(output, format="trig")
    ids = []
    for subject, _, _, head in ds.quads((None, RDF.type, np.Nanopublication, None)):
        graph = ds.graph(head)
        info = graph.value(subject, np.hasPublicationInfo)
        ds.graph(info).set((subject, prov.generatedAtTime, Literal("2026-10-25T12:00:00+00:00", datatype=XSD.dateTime)))
        ids.append({"id": str(subject), "assertionId": str(graph.value(subject, np.hasAssertion)), "provenanceId": str(graph.value(subject, np.hasProvenance)), "pubinfoId": str(info)})
    (root / "synthetic.ids.json").write_text(json.dumps(sorted(ids, key=lambda row: row["id"]), indent=2) + "\n")
    (root / "synthetic.expected.trig").write_text("# AUTHORED-BY Codex GPT-6.1-Sol — generated by the Python reference builder\n" + ds.serialize(format="trig"))

# Extra canonicalization edge cases, independently evaluated by RDFlib.
import importlib.util
spec = importlib.util.spec_from_file_location("reference_builder", sys.argv[1])
reference = importlib.util.module_from_spec(spec)
spec.loader.exec_module(reference)
cases = [
    ('symmetric', '_:a schema:knows _:b . _:b schema:knows _:a .'),
    ('disconnected', '_:a schema:name "same" . _:b schema:name "same" .'),
    ('cycle', '_:a schema:knows _:b . _:b schema:knows _:c . _:c schema:knows _:a .'),
    ('unequal', '_:a schema:knows _:b . _:b schema:knows _:c . _:c schema:name "end" .'),
    ('branch', '_:a schema:knows _:b, _:c . _:b schema:name "same" . _:c schema:name "same" .'),
    ('multiline', '_:a schema:name """A line\nanother "line" and \\\\slash""" . _:b schema:name "Autre"@fr .'),
    ('unicode-order', '<https://example.org/𐀀> schema:name "𐀀" . <https://example.org/\ue000> schema:name "\ue000" .'),
    ('terminal-quote', '_:a schema:name """A line\nending with a \\"""" . _:b schema:name "different" .'),
    ('typed', '_:a schema:value "0001"^^xsd:integer, "1"^^xsd:boolean, "2026-01-01T00:00:00.1Z"^^xsd:dateTime . _:b schema:value "false"^^xsd:boolean .'),
    ('unequal-regular', '_:a schema:knows _:b . _:b schema:knows _:c . _:c schema:knows _:a . _:d schema:knows _:e . _:e schema:knows _:f . _:f schema:knows _:g . _:g schema:knows _:d .'),
    ('self-loop', '_:a schema:knows _:a . _:b schema:knows _:b .'),
]
rows = []
for name, assertion in cases:
    identifier, graph = reference.canonicalise(reference.parse_assertion(assertion))
    rows.append({"name": name, "assertion": assertion, "id": str(identifier), "graph": graph.serialize(format="nt")})
(root / "canonical.json").write_text(json.dumps({"$comment": "AUTHORED-BY Codex GPT-6.1-Sol; generated using RDFlib 7.1.4", "cases": rows}, indent=2) + "\n")
