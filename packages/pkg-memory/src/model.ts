/** How a claim entered the graph, orthogonal to validity. */
export const EPISTEMIC_STATUSES = [
  "Documented",
  "DocumentedViaSummary",
  "SelfReportedExplicit",
  "SelfReportedHedged",
  "ThirdPartyReported",
  "Inferred",
  "Mentioned",
] as const;
/** Current standing of a claim. */
export const VALIDITY_STATUSES = [
  "Current",
  "Superseded",
  "Contradicted",
  "Retracted",
  "Historical",
] as const;
/** PKG epistemic token. */
export type EpistemicStatus = (typeof EPISTEMIC_STATUSES)[number];
/** PKG validity token. */
export type ValidityStatus = (typeof VALIDITY_STATUSES)[number];
/** Evidence item in the Python batch contract. */
export interface Evidence {
  source: string;
  message_id?: string;
  timestamp?: string;
  speaker?: string;
  locator?: string;
  quote?: string;
}
/** One claim; Turtle assertions are trusted RDF syntax, never interpolated tool input. */
export interface Claim {
  id: string;
  assertion: string | DatasetCore;
  epistemic: EpistemicStatus;
  validity?: ValidityStatus;
  hedge?: string;
  categories?: string[];
  note?: string;
  attributed_to?: string;
  evidence?: Evidence[];
  supersedes?: string[];
  contradicts?: string[];
  inference?: { rule: string; inputs?: string[] };
}
/** Source metadata; local file hashes must be supplied explicitly. */
export interface Source {
  id: string;
  kind: "codex-thread" | "claude-session" | "document" | "email";
  thread_id?: string;
  title?: string;
  cwd?: string;
  model?: string;
  originator?: string;
  rollout_path?: string;
  created?: string;
  url?: string;
  path?: string;
  sha256?: string;
  author?: string;
  date?: string;
  derived_from?: string[];
}
/** A reusable entity registry record. */
export interface Entity {
  id: string;
  label: string;
  types?: string[];
  aliases?: string[];
  same_as?: string[];
  url?: string;
  note?: string;
}
/** Batch contract of np_builder.py, with owner identity passed separately. */
export interface Batch {
  batch_id: string;
  worker: { agent_id: string; agent_label: string; started?: string; finished?: string };
  sources?: Source[];
  entities?: Entity[];
  claims: Claim[];
  skipped_sensitive?: { category: string; source?: string; note?: string }[];
}
/** Build identity and clock seam. */
export interface BuildOptions {
  owner: string;
  generatedAt?: string;
}
/** Graph-scoped parsed annotation. */
export interface NanopubEvidence {
  id: string;
  source: string;
  quote?: string;
  locator?: string;
}
/** Nanopublication metadata; assertion data remains available in the dataset. */
export interface Nanopublication {
  id: string;
  assertionId: string;
  provenanceId: string;
  pubinfoId: string;
  epistemic: EpistemicStatus;
  validity: ValidityStatus;
  categories: string[];
  attributedTo: string[];
  hedge?: string;
  evidence: NanopubEvidence[];
  supersedes: string[];
  contradicts: string[];
  batch: string;
  identifier: string;
  generatedAt: string;
  agent: string;
}
/** Complete dataset and per-nanopub views, including shared assertion graphs. */
export interface Nanopublications {
  dataset: Store;
  nanopubs: Nanopublication[];
}

function known<T extends string>(value: string, values: readonly T[]): T {
  if (!values.includes(value as T)) throw new Error(`Unknown status: ${value}`);
  return value as T;
}
function localFile(value: string): string {
  if (!value.startsWith("/")) throw new Error("Expected absolute source path");
  return pathToFileURL(value).href;
}
/** Parse a prefixed assertion body with the reference builder's namespace bindings. */
export async function parseAssertion(body: string, owner: string): Promise<DatasetCore> {
  const webId = safeHttpIri(owner);
  if (webId === undefined) throw new Error("Expected owner WebID");
  // Prefix declarations are generated by the sanctioned Writer; input is RDF syntax.
  const preamble = await serialize([], {
    prefixes: { ...NS, me: webId },
    emptyAsEmptyString: false,
  });
  const dataset = await parseReferenceRdf(preamble + body, "text/turtle");
  validateLiterals(dataset);
  return dataset;
}
/** Port of the reference builder; atomic on invalid claims or references. */
export async function buildNanopublications(
  batch: Batch,
  options: BuildOptions,
): Promise<Nanopublications> {
  const owner = safeHttpIri(options.owner);
  if (owner === undefined) throw new Error("Expected owner WebID");
  const now = dateTime(options.generatedAt ?? new Date().toISOString().replace(/\.\d{3}Z$/, "Z"));
  const dataset = new Store();
  const sources = new Store();
  const entities = new Store();
  const activity = pkgId("batch", batch.batch_id, "activity");
  const sourcesId = pkgId("batch", batch.batch_id, "sources");
  const agent = expand(batch.worker.agent_id, owner);
  const node = (g: Store, s: string | Term): RdfNode => new RdfNode(s, g);
  const type = `${NS.rdf}type`;
  node(sources, agent)
    .link(type, `${NS.prov}SoftwareAgent`)
    .text(`${NS.rdfs}label`, batch.worker.agent_label);
  const act = node(sources, activity)
    .link(type, `${NS.prov}Activity`)
    .text(`${NS.rdfs}label`, `PKG extraction batch ${batch.batch_id}`)
    .link(`${NS.prov}wasAssociatedWith`, agent);
  if (batch.worker.started)
    act.text(`${NS.prov}startedAtTime`, dateTime(batch.worker.started), `${NS.xsd}dateTime`);
  if (batch.worker.finished)
    act.text(`${NS.prov}endedAtTime`, dateTime(batch.worker.finished), `${NS.xsd}dateTime`);
  const sourceIds = new Map<string, string>();
  for (const s of batch.sources ?? []) {
    if (sourceIds.has(s.id)) throw new Error("Duplicate source id");
    let source: string;
    if (s.kind === "codex-thread" || s.kind === "claude-session") {
      if (
        !s.thread_id ||
        !/^(?:[\da-f]{32}|[\da-f]{8}(?:-[\da-f]{4}){3}-[\da-f]{12})$/i.test(s.thread_id)
      )
        throw new Error("Invalid thread UUID");
      source = messageId(s.thread_id);
      const thread = node(sources, source)
        .link(type, `${NS.schema}Conversation`)
        .text(`${NS.dcterms}identifier`, s.thread_id)
        .text(`${NS.schema}provider`, s.kind === "codex-thread" ? "OpenAI Codex" : "Claude Code");
      for (const [key, prop] of [
        ["title", "name"],
        ["cwd", "workLocation"],
        ["model", "instrument"],
        ["originator", "applicationCategory"],
      ] as const)
        if (s[key]) thread.text(NS.schema + prop, s[key]);
      if (s.rollout_path) thread.link(`${NS.prov}atLocation`, localFile(s.rollout_path));
      if (s.created)
        thread.text(`${NS.schema}dateCreated`, dateTime(s.created), `${NS.xsd}dateTime`);
    } else if (s.kind === "document" || s.kind === "email") {
      if (!s.url && !s.path) throw new Error("Source needs url or path");
      source = s.url ? iri(s.url) : localFile(s.path as string);
      const document = node(sources, source).link(
        type,
        NS.schema + (s.kind === "document" ? "DigitalDocument" : "EmailMessage"),
      );
      if (s.title) document.text(`${NS.schema}name`, s.title);
      if (s.sha256) document.text(`${NS.schema}sha256`, s.sha256);
      if (s.author) document.link(`${NS.schema}author`, expand(s.author, owner));
      if (s.date) document.text(`${NS.schema}dateCreated`, s.date, `${NS.xsd}date`);
      for (const parent of s.derived_from ?? []) document.link(`${NS.prov}wasDerivedFrom`, parent);
    } else throw new Error("Unknown source kind");
    sourceIds.set(s.id, source);
    act.link(`${NS.prov}used`, source);
  }
  for (const e of batch.entities ?? []) {
    const entity = node(entities, expand(e.id, owner))
      .text(`${NS.rdfs}label`, e.label)
      .link(`${NS.prov}wasGeneratedBy`, activity);
    for (const t of e.types ?? []) entity.link(type, expand(t, owner));
    for (const alias of e.aliases ?? []) entity.text(`${NS.skos}altLabel`, alias);
    for (const same of e.same_as ?? []) entity.link(`${NS.schema}sameAs`, same);
    if (e.url) entity.link(`${NS.schema}url`, e.url);
    if (e.note) entity.text(`${NS.rdfs}comment`, e.note);
  }
  const claims = new Map<
    string,
    { id: string; assertion: ReturnType<typeof canonicalizeAssertion>; prov: Store }
  >();
  for (const c of batch.claims) {
    if (claims.has(c.id)) throw new Error("Duplicate claim id");
    known(c.epistemic, EPISTEMIC_STATUSES);
    known(c.validity ?? "Current", VALIDITY_STATUSES);
    const assertion = canonicalizeAssertion(
      typeof c.assertion === "string" ? await parseAssertion(c.assertion, owner) : c.assertion,
    );
    claims.set(c.id, { id: pkgId("np", batch.batch_id, c.id), assertion, prov: new Store() });
  }
  const ref = (id: string) => {
    const c = claims.get(id);
    if (!c) throw new Error(`Unknown claim reference: ${id}`);
    return c;
  };
  for (const c of batch.claims) {
    const { id, assertion, prov } = ref(c.id);
    const head = new Store();
    const info = new Store();
    node(head, id)
      .link(type, `${NS.np}Nanopublication`)
      .link(`${NS.np}hasAssertion`, assertion.id)
      .link(`${NS.np}hasProvenance`, `${id}#provenance`)
      .link(`${NS.np}hasPublicationInfo`, `${id}#pubinfo`);
    putGraph(dataset, id, head);
    putGraph(dataset, assertion.id, assertion.dataset);
    const a = node(prov, assertion.id)
      .link(`${NS.pkg}epistemicStatus`, NS.pkg + c.epistemic)
      .link(`${NS.pkg}validityStatus`, NS.pkg + (c.validity ?? "Current"))
      .link(`${NS.prov}wasGeneratedBy`, activity);
    if (c.hedge) a.text(`${NS.pkg}hedgeMarker`, c.hedge);
    if (c.note) a.text(`${NS.rdfs}comment`, c.note);
    for (const cat of c.categories ?? []) a.link(`${NS.dpv}hasPersonalData`, expand(cat, owner));
    if (c.attributed_to) a.link(`${NS.prov}wasAttributedTo`, expand(c.attributed_to, owner));
    else if (["SelfReportedExplicit", "SelfReportedHedged", "Mentioned"].includes(c.epistemic))
      a.link(`${NS.prov}wasAttributedTo`, owner);
    const times: string[] = [];
    for (const [i, ev] of (c.evidence ?? []).entries()) {
      const src = sourceIds.get(ev.source);
      if (!src) throw new Error("Unknown evidence source");
      const ann = pkgId("np", batch.batch_id, c.id, "ann", String(i));
      const target = df.blankNode();
      a.link(`${NS.prov}wasDerivedFrom`, ann);
      node(prov, ann)
        .link(type, `${NS.oa}Annotation`)
        .link(`${NS.oa}motivatedBy`, `${NS.oa}linking`)
        .link(`${NS.oa}hasBody`, assertion.id)
        .add(`${NS.oa}hasTarget`, target);
      const resource = node(prov, target).link(type, `${NS.oa}SpecificResource`);
      if (ev.message_id) {
        const m = messageId(ev.message_id);
        resource.link(`${NS.oa}hasSource`, m);
        const message = node(sources, m)
          .link(type, `${NS.schema}Message`)
          .text(`${NS.dcterms}identifier`, ev.message_id)
          .link(`${NS.schema}isPartOf`, src);
        if (ev.timestamp)
          message.text(`${NS.schema}dateSent`, dateTime(ev.timestamp), `${NS.xsd}dateTime`);
        const speaker = ev.speaker ?? "me";
        if (speaker === "me") message.link(`${NS.schema}sender`, owner);
        else if (speaker.includes(":")) message.link(`${NS.schema}sender`, expand(speaker, owner));
        else message.text(`${NS.schema}sender`, speaker);
      } else {
        resource.link(`${NS.oa}hasSource`, src);
        if (ev.locator) {
          const selector = df.blankNode();
          resource.add(`${NS.oa}hasSelector`, selector);
          node(prov, selector)
            .link(type, `${NS.oa}FragmentSelector`)
            .text(`${NS.rdf}value`, ev.locator);
        }
      }
      if (ev.quote) {
        if ([...ev.quote].length > 300) throw new Error("Quote longer than 300 characters");
        const quote = df.blankNode();
        resource.add(`${NS.oa}hasSelector`, quote);
        node(prov, quote).link(type, `${NS.oa}TextQuoteSelector`).text(`${NS.oa}exact`, ev.quote);
      }
      if (ev.timestamp) {
        times.push(dateTime(ev.timestamp));
      }
    }
    const earliest = times.sort(
      (a, b) =>
        Date.parse(a) - Date.parse(b) ||
        // Date.parse compares milliseconds; normalized fractions retain the
        // reference's six-digit precision for instants within one millisecond.
        (a.match(/\.\d{6}/)?.[0] ?? "").localeCompare(b.match(/\.\d{6}/)?.[0] ?? ""),
    )[0];
    if (earliest) a.text(`${NS.prov}generatedAtTime`, dateTime(earliest), `${NS.xsd}dateTime`);
    for (const old of c.supersedes ?? []) {
      const previous = ref(old);
      a.link(`${NS.prov}wasRevisionOf`, previous.assertion.id);
      if (earliest)
        node(previous.prov, previous.assertion.id).text(
          `${NS.prov}invalidatedAtTime`,
          dateTime(earliest),
          `${NS.xsd}dateTime`,
        );
    }
    for (const other of c.contradicts ?? [])
      a.link(`${NS.pkg}contradicts`, ref(other).assertion.id);
    if (c.inference) {
      if (c.epistemic !== "Inferred")
        throw new Error("Inference requires Inferred epistemic status");
      const inference = pkgId("np", batch.batch_id, c.id, "inference");
      a.link(`${NS.prov}wasGeneratedBy`, inference);
      const association = df.blankNode();
      const inf = node(prov, inference)
        .link(type, `${NS.prov}Activity`)
        .add(`${NS.prov}qualifiedAssociation`, association);
      node(prov, association)
        .link(type, `${NS.prov}Association`)
        .link(`${NS.prov}agent`, agent)
        .link(`${NS.prov}hadPlan`, expand(c.inference.rule, owner));
      for (const input of c.inference.inputs ?? [])
        inf.link(`${NS.prov}used`, ref(input).assertion.id);
    }
    node(info, id)
      .text(`${NS.prov}generatedAtTime`, now, `${NS.xsd}dateTime`)
      .link(`${NS.prov}wasAttributedTo`, agent)
      .link(`${NS.prov}wasGeneratedBy`, activity)
      .text(`${NS.pkg}batch`, batch.batch_id)
      .text(`${NS.dcterms}identifier`, `${batch.batch_id}/${c.id}`);
    putGraph(dataset, `${id}#pubinfo`, info);
  }
  for (const c of claims.values()) putGraph(dataset, `${c.id}#provenance`, c.prov);
  for (const [i, s] of (batch.skipped_sensitive ?? []).entries()) {
    const skipped = node(sources, pkgId("batch", batch.batch_id, "skipped", String(i)))
      .link(type, `${NS.prov}Entity`)
      .text(`${NS.rdfs}label`, "intentionally unrecorded sensitive value")
      .link(`${NS.dpv}hasPersonalData`, expand(s.category, owner))
      .link(`${NS.prov}wasGeneratedBy`, activity);
    if (s.note) skipped.text(`${NS.rdfs}comment`, s.note);
    const source = s.source === undefined ? undefined : sourceIds.get(s.source);
    if (source) skipped.link(`${NS.prov}wasDerivedFrom`, source);
  }
  putGraph(dataset, sourcesId, sources);
  putGraph(dataset, pkgId("batch", batch.batch_id, "entities"), entities);
  if (batch.claims.length === 0) return { dataset, nanopubs: [] };
  return readNanopublications(dataset);
}

function iriValues(node: RdfNode, predicate: string): string[] {
  return [...node.terms(predicate)]
    .map((term) => {
      if (term.termType !== "NamedNode") throw new Error("Expected IRI");
      return iri(term.value);
    })
    .sort();
}
function optionalText(node: RdfNode, predicate: string): string | undefined {
  return node.terms(predicate).size === 0 ? undefined : node.oneText(predicate);
}
function readNanopublications(dataset: Store): Nanopublications {
  validateLiterals(dataset);
  const ids = new Set<string>();
  // A head links its component graphs from the nanopub's own named graph.
  // Type statements elsewhere (including assertion/entity graphs) are data.
  for (const predicate of ["hasAssertion", "hasProvenance", "hasPublicationInfo"]) {
    for (const q of dataset.match(null, df.namedNode(NS.np + predicate))) {
      if (q.subject.termType === "NamedNode" && q.subject.equals(q.graph)) ids.add(q.subject.value);
    }
  }
  if (!ids.size) throw new Error("No nanopublications");
  const nanopubs = [...ids].sort().map((id) => {
    const head = new RdfNode(id, graph(dataset, id));
    if (!iriValues(head, `${NS.rdf}type`).includes(`${NS.np}Nanopublication`))
      throw new Error("Invalid nanopub head type");
    const assertionId = head.oneIri(`${NS.np}hasAssertion`);
    const provenanceId = head.oneIri(`${NS.np}hasProvenance`);
    const pubinfoId = head.oneIri(`${NS.np}hasPublicationInfo`);
    if (new Set([id, assertionId, provenanceId, pubinfoId]).size !== 4)
      throw new Error("Nanopub graphs must be distinct");
    for (const name of [assertionId, provenanceId, pubinfoId])
      if (graph(dataset, name).size === 0) throw new Error("Missing nanopub graph");
    const p = graph(dataset, provenanceId);
    const a = new RdfNode(assertionId, p);
    const info = new RdfNode(id, graph(dataset, pubinfoId));
    const evidence = iriValues(a, `${NS.prov}wasDerivedFrom`).map((annotationId) => {
      const annotation = new RdfNode(annotationId, p);
      if (
        !iriValues(annotation, `${NS.rdf}type`).includes(`${NS.oa}Annotation`) ||
        annotation.oneIri(`${NS.oa}hasBody`) !== assertionId
      )
        throw new Error("Invalid evidence annotation");
      const target = new RdfNode(annotation.one(`${NS.oa}hasTarget`), p);
      const result: NanopubEvidence = {
        id: annotationId,
        source: target.oneIri(`${NS.oa}hasSource`),
      };
      for (const selector of target.terms(`${NS.oa}hasSelector`)) {
        const selection = new RdfNode(selector, p);
        const types = iriValues(selection, `${NS.rdf}type`);
        if (types.includes(`${NS.oa}TextQuoteSelector`)) {
          if (result.quote !== undefined) throw new Error("Multiple evidence quote selectors");
          result.quote = selection.oneText(`${NS.oa}exact`);
        }
        if (types.includes(`${NS.oa}FragmentSelector`)) {
          if (result.locator !== undefined) throw new Error("Multiple evidence locator selectors");
          result.locator = selection.oneText(`${NS.rdf}value`);
        }
      }
      return result;
    });
    return {
      id,
      assertionId,
      provenanceId,
      pubinfoId,
      epistemic: known(
        a.oneIri(`${NS.pkg}epistemicStatus`).replace(NS.pkg, ""),
        EPISTEMIC_STATUSES,
      ),
      validity: known(a.oneIri(`${NS.pkg}validityStatus`).replace(NS.pkg, ""), VALIDITY_STATUSES),
      categories: iriValues(a, `${NS.dpv}hasPersonalData`),
      attributedTo: iriValues(a, `${NS.prov}wasAttributedTo`),
      hedge: optionalText(a, `${NS.pkg}hedgeMarker`),
      evidence,
      supersedes: iriValues(a, `${NS.prov}wasRevisionOf`),
      contradicts: iriValues(a, `${NS.pkg}contradicts`),
      batch: info.oneText(`${NS.pkg}batch`),
      identifier: info.oneText(`${NS.dcterms}identifier`),
      generatedAt: info.oneDateTime(`${NS.prov}generatedAtTime`),
      agent: info.oneIri(`${NS.prov}wasAttributedTo`),
    };
  });
  return { dataset, nanopubs };
}
/** Serialize all named graphs as TriG through the suite Writer. */
export async function serializeNanopublications(value: Nanopublications): Promise<string> {
  for (const q of value.dataset)
    for (const term of [q.subject, q.predicate, q.object, q.graph]) validateTermSafety(term);
  validateLiterals(value.dataset);
  return serialize([...value.dataset], { format: "application/trig", prefixes: { ...NS } });
}
/** Parse TriG and read metadata only from each nanopub's linked graphs. */
export async function parseNanopublications(
  trig: string,
  baseIRI?: string,
): Promise<Nanopublications> {
  const dataset = await parseReferenceRdf(trig, "application/trig", baseIRI);
  return readNanopublications(new Store([...dataset]));
}
