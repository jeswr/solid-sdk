// AUTHORED-BY Codex GPT-6.1-Sol
// Generate the compatibility sidecar from the immutable pre-VOC-02 sources.
// Historical namespace: https://w3id.org/jeswr/ (never imported by the ontologies).
// Run from any directory; optionally pass a different pre-rebase git revision.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { DataFactory, Parser, Writer } from "n3";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WORKSPACE = join(ROOT, "..", "..");
const sourceRef = process.argv[2] ?? "6b46636d065fd49f4a07d86c92cacad8ef4bea96";
const oldRoot = new URL("/jeswr/", "https://w3id.org").href;
const newRoot = "https://jeswr.org/ns/";
const RDF = "http://www.w3.org/1999/02/22-rdf-syntax-ns#";
const RDFS = "http://www.w3.org/2000/01/rdf-schema#";
const OWL = "http://www.w3.org/2002/07/owl#";
const { namedNode, quad } = DataFactory;
const git = (...args) => execFileSync("git", args, { cwd: WORKSPACE, encoding: "utf8" });
const packagePath = relative(WORKSPACE, ROOT);
const files = git("ls-tree", "-r", "--name-only", sourceRef, "--", packagePath)
  .trim()
  .split("\n")
  .filter((path) => {
    const rel = relative(packagePath, path);
    return (
      ["fedapp.ttl", "fedreg.ttl", "task.ttl"].includes(rel) ||
      (rel.startsWith("sectors/") && basename(path) === `${basename(dirname(path))}.ttl`)
    );
  });
if (files.length !== 17)
  throw new Error(`Expected 17 pre-rebase vocabularies, got ${files.length}`);

const terms = new Map();
for (const file of files) {
  const quads = new Parser().parse(git("show", `${sourceRef}:${file}`));
  const ontology = quads.find(
    (q) => q.predicate.value === `${RDF}type` && q.object.value === `${OWL}Ontology`,
  )?.subject.value;
  if (!ontology?.startsWith(oldRoot)) throw new Error(`${file}: not a legacy ontology`);
  for (const q of quads) {
    if (q.subject.termType !== "NamedNode" || !q.subject.value.startsWith(`${ontology}#`)) continue;
    const types = terms.get(q.subject.value) ?? new Set();
    if (q.predicate.value === `${RDF}type`) types.add(q.object.value);
    terms.set(q.subject.value, types);
  }
}

const writer = new Writer({ prefixes: { owl: OWL } });
const counts = { equivalentClass: 0, equivalentProperty: 0, sameAs: 0 };
for (const [iri, types] of [...terms].sort(([a], [b]) => a.localeCompare(b))) {
  if (types.size === 0) throw new Error(`${iri}: no declared type; cannot classify legacy term`);
  const relation =
    types.has(`${OWL}Class`) || types.has(`${RDFS}Class`)
      ? "equivalentClass"
      : [
            `${RDF}Property`,
            `${OWL}ObjectProperty`,
            `${OWL}DatatypeProperty`,
            `${OWL}AnnotationProperty`,
          ].some((type) => types.has(type))
        ? "equivalentProperty"
        : "sameAs";
  writer.addQuad(
    quad(
      namedNode(iri),
      namedNode(`${OWL}${relation}`),
      namedNode(newRoot + iri.slice(oldRoot.length)),
    ),
  );
  counts[relation] += 1;
}
const turtle = await new Promise((resolve, reject) => {
  writer.end((error, result) => (error ? reject(error) : resolve(result)));
});
const header = `# AUTHORED-BY Codex GPT-6.1-Sol
# Generated by scripts/legacy-w3id-alignments.mjs from git ${sourceRef}.
# Mode-A compatibility sidecar: opt-in only; NEVER owl:import this file.
# OWL equivalences have entailments when explicitly loaded. This sidecar is
# excluded from dist/vocab.nt and every ontology's reasoned import closure.
# Exactly one old-to-new mapping per declared term; external terms are omitted.
\n`;
writeFileSync(join(ROOT, "legacy-w3id-alignments.ttl"), header + turtle);
console.log(
  `Legacy mappings: ${terms.size} terms from ${files.length} ontologies (${JSON.stringify(counts)})`,
);
